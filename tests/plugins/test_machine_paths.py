"""The third answer: looking where this project's own installer puts things.

An operator who ran ``envs/bootstrap.sh`` has already told MolCascade where its
engines are -- by installing them where the script installs them.  Making them
say it a second time, in a config field or a shell profile, is asking for
information the machine already has, and it was the last remaining reason a
cascade generated by the builder would not run without being edited first.

So the resolution order is three deep, and this file is about the third step and
its boundaries:

* discovery only ever *supplies* a value.  It cannot reject one, which is why it
  is safe to do from a Pydantic validator: a laptop that finds nothing leaves the
  field blank, and blank is valid.
* the config wins over the environment, and the environment wins over discovery.
  A host that has two KarmaDocks installed and names one must get the one it
  named.
* a discovered path is validated exactly as a typed one is, and travels into the
  method identity and the run record the same way.  Nothing becomes less
  reproducible for having been found rather than typed.
* what is found is a *specific absolute path this project writes*, not a name
  resolved on ``PATH``.  That distinction is the whole reason the adapters may do
  this while still refusing to accept ``unidock`` as an executable.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

from molcascade.plugins.builtin._machine_paths import (
    MachinePath,
    backend_root,
    conda_environment,
    conda_environment_roots,
    discover_machine_path,
    engine_path,
    fill_machine_paths,
)
from molcascade.plugins.builtin.aizynthfinder import AiZynthFinderConfig
from molcascade.plugins.builtin.boltz2 import Boltz2Config
from molcascade.plugins.builtin.docking.gnina import GninaConfig
from molcascade.plugins.builtin.docking.karmadock import KarmaDockConfig
from molcascade.plugins.builtin.docking.unidock import UniDockConfig
from molcascade.plugins.builtin.openadmet import OpenADMETConfig

_KARMADOCK_SITE = {
    "receptor_path": "/campaign/receptor.pdb",
    "reference_ligand_path": "/campaign/ligand.mol2",
}
_UNIDOCK_SITE = {
    "receptor_path": "/campaign/receptor.pdb",
    "receptor_pdbqt_path": "/campaign/receptor.pdbqt",
    "center_x": 1.0,
    "center_y": 2.0,
    "center_z": 3.0,
    "size_x": 20.0,
    "size_y": 20.0,
    "size_z": 20.0,
}


def _install(path: Path, *, executable: bool = False) -> Path:
    """Create a file where a candidate expects one."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("", encoding="utf-8")
    if executable:
        path.chmod(0o755)
    return path


# ------------------------------------------------------- where discovery looks


def test_the_backend_root_is_the_one_the_bootstrap_script_uses(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Two defaults that can drift are one bug waiting for a new machine.

    ``envs/bootstrap.sh`` reads the same variable with the same fallback; if it
    installed into one directory and this looked in another, discovery would
    fail on exactly the hosts that had done everything right.
    """

    monkeypatch.setenv("MOLCASCADE_BACKEND_ROOT", "/srv/engines")
    assert backend_root() == Path("/srv/engines")
    monkeypatch.delenv("MOLCASCADE_BACKEND_ROOT")
    monkeypatch.setenv("HOME", "/home/someone")
    assert backend_root() == Path("/home/someone/molcascade-backends")


def test_a_sibling_environment_is_looked_for_beside_this_one_and_below_it(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The running interpreter is the landmark, and it can be either shape.

    MolCascade installed into a conda environment sits beside the engines'
    environments; MolCascade installed into the base environment sits one level
    above them.  Both are ordinary, so both are searched.
    """

    monkeypatch.delenv("MOLCASCADE_CONDA_ENVS", raising=False)
    monkeypatch.delenv("CONDA_ENVS_DIRS", raising=False)
    monkeypatch.setattr(sys, "prefix", "/opt/conda/envs/prism")
    assert conda_environment("karmadock", "bin/python") == (
        Path("/opt/conda/envs/karmadock/bin/python"),
        Path("/opt/conda/envs/prism/envs/karmadock/bin/python"),
    )


def test_conda_s_own_variable_is_honoured_before_the_guesses(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """``CONDA_ENVS_DIRS`` is where conda itself looks, so it is where to look.

    Added to the guesses rather than replacing them: a host can have it set and
    still keep the engine environments beside this one.
    """

    monkeypatch.delenv("MOLCASCADE_CONDA_ENVS", raising=False)
    monkeypatch.setenv("CONDA_ENVS_DIRS", os.pathsep.join(["/data/envs", "/other/envs"]))
    monkeypatch.setattr(sys, "prefix", "/opt/conda/envs/prism")
    roots = conda_environment_roots()
    assert roots[:2] == (Path("/data/envs"), Path("/other/envs"))
    assert Path("/opt/conda/envs") in roots


def test_an_explicit_envs_root_replaces_the_guesses(monkeypatch: pytest.MonkeyPatch) -> None:
    """For a host this cannot infer: a ``--prefix`` tree, a mamba root, a venv.

    Replacing rather than extending, because the point of setting it is that the
    inferred locations are wrong.
    """

    monkeypatch.setenv("MOLCASCADE_CONDA_ENVS", "/somewhere/specific")
    monkeypatch.setattr(sys, "prefix", "/opt/conda/envs/prism")
    assert conda_environment_roots() == (Path("/somewhere/specific"),)


def test_discovery_returns_the_first_candidate_that_exists(tmp_path: Path) -> None:
    second = _install(tmp_path / "second" / "unidock", executable=True)
    spec = MachinePath(
        field="executable",
        label="the Uni-Dock binary",
        candidates=(tmp_path / "first" / "unidock", second),
    )
    assert discover_machine_path(spec) == str(second)


def test_discovery_finds_nothing_when_nothing_is_installed(tmp_path: Path) -> None:
    """Which is the case that has to stay quiet.

    Every config model runs this during validation, including on a laptop
    reviewing a cascade it will never run.  Finding nothing must be an ordinary
    outcome, not an error.
    """

    spec = MachinePath(
        field="executable",
        label="the Uni-Dock binary",
        candidates=(tmp_path / "absent" / "unidock",),
    )
    assert discover_machine_path(spec) is None


# --------------------------------------------------------- the order of answers


def test_the_config_wins_over_the_environment_and_the_environment_over_the_disk(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """All three answers present at once, so the precedence is unambiguous."""

    found = _install(tmp_path / "envs" / "unidock" / "bin" / "unidock", executable=True)
    monkeypatch.setenv("MOLCASCADE_CONDA_ENVS", str(tmp_path / "envs"))

    # Disk only.
    assert UniDockConfig(**_UNIDOCK_SITE).executable == str(found)

    # Environment beats disk.
    monkeypatch.setenv("MOLCASCADE_UNIDOCK_EXECUTABLE", "/opt/exported/unidock")
    assert UniDockConfig(**_UNIDOCK_SITE).executable == "/opt/exported/unidock"

    # Config beats both.
    named = UniDockConfig(executable="/opt/named/unidock", **_UNIDOCK_SITE)
    assert named.executable == "/opt/named/unidock"


def test_a_discovered_path_is_validated_like_a_typed_one(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """Being found is not a reason to skip the absolute-path check.

    A relative candidate could only come from a bug in a candidate list, but the
    field's contract is what the rest of the system relies on -- the path goes
    into the method identity and into the subprocess launch -- so it is enforced
    for every route in.
    """

    monkeypatch.chdir(tmp_path)
    _install(tmp_path / "relative-unidock", executable=True)
    spec = MachinePath(
        field="executable",
        label="the Uni-Dock binary",
        candidates=(Path("relative-unidock"),),
    )
    discovered = discover_machine_path(spec)
    assert discovered == "relative-unidock"
    with pytest.raises(ValueError, match="must be an absolute path"):
        engine_path(discovered, field="executable", engine_id="unidock")


def test_a_field_with_a_non_string_value_is_left_for_pydantic_to_report() -> None:
    """Discovery must not paper over the wrong *type* of value.

    Replacing ``executable: 7`` with a discovered path would turn a config
    someone got visibly wrong into one that silently ran something else.
    """

    spec = MachinePath(field="executable", label="the engine's program")
    data = {"executable": 7}
    assert fill_machine_paths(data, engine_id="unidock", paths=[spec]) == data


def test_an_empty_list_is_an_unanswered_question_like_an_empty_string(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """A path that may be given more than once is blank when it is given none.

    OpenADMET takes one model directory per ensemble member, so its field holds
    a list rather than a string -- and a builder that always writes the key
    writes ``[]``.  Reading that as "already answered" would switch discovery
    off for ever, on every machine, for the one field whose default the operator
    is least likely to have typed.
    """

    found = _install(tmp_path / "envs" / "openadmet" / "models" / "herg" / "anvil_training" / "w")
    spec = next(spec for spec in OpenADMETConfig.installed_paths() if spec.field == "model_dir")
    monkeypatch.setenv("MOLCASCADE_OPENADMET_MODEL_DIR", str(found.parent))

    filled = fill_machine_paths({"model_dir": []}, engine_id="openadmet", paths=[spec])
    assert filled["model_dir"] == str(found.parent)

    # And a list that says something is still the operator's to keep.
    named = {"model_dir": ["/campaign/fold-1", "/campaign/fold-2"]}
    assert fill_machine_paths(named, engine_id="openadmet", paths=[spec]) == named


def test_filling_does_not_mutate_the_config_it_was_given(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """A ``mode="before"`` validator receives the caller's own dict.

    The compiler validates the same stage config more than once, and a validator
    that edited its input in place would make the second pass see a machine path
    the cascade never carried.
    """

    found = _install(tmp_path / "envs" / "unidock" / "bin" / "unidock", executable=True)
    monkeypatch.setenv("MOLCASCADE_CONDA_ENVS", str(tmp_path / "envs"))
    spec = next(spec for spec in UniDockConfig.installed_paths() if spec.field == "executable")
    original = {"executable": ""}
    filled = fill_machine_paths(original, engine_id="unidock", paths=[spec])
    assert filled["executable"] == str(found)
    assert original == {"executable": ""}


