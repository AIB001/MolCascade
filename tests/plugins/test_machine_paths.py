def test_every_engine_looks_where_the_bootstrap_script_installs_it(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    """The paths in ``envs/bootstrap.sh``, laid out and then found.

    Written as one test over one directory tree because the guarantee is about
    the tree: an operator runs the script once and every engine in the cascade
    resolves, or the layout and the search have drifted apart.
    """

    envs = tmp_path / "envs"
    backends = tmp_path / "molcascade-backends"
    data = tmp_path / "aizynth-data"
    monkeypatch.setenv("MOLCASCADE_CONDA_ENVS", str(envs))
    monkeypatch.setenv("MOLCASCADE_BACKEND_ROOT", str(backends))
    monkeypatch.setenv("MOLCASCADE_AIZYNTH_DATA", str(data))

    karmadock_python = _install(envs / "karmadock" / "bin" / "python", executable=True)
    checkout = backends / "KarmaDock"
    _install(checkout / "utils" / "virtual_screening.py")
    _install(checkout / "trained_models" / "karmadock_screening.pkl")
    unidock = _install(envs / "unidock" / "bin" / "unidock", executable=True)
    gnina = _install(backends / "bin" / "gnina", executable=True)
    aizynthcli = _install(envs / "aizynth" / "bin" / "aizynthcli", executable=True)
    config_yml = _install(data / "config.yml")
    openadmet = _install(envs / "openadmet" / "bin" / "openadmet", executable=True)
    released = backends / "openadmet-models" / "herg-chemeleon-baseline" / "anvil_training"
    _install(released / "model.pth")
    _install(released / "model.json")

    karmadock = KarmaDockConfig(**_KARMADOCK_SITE)
    assert karmadock.executable == str(karmadock_python)
    assert karmadock.repo_path == str(checkout)
    assert UniDockConfig(**_UNIDOCK_SITE).executable == str(unidock)
    assert GninaConfig(
        receptor_path="/campaign/receptor.pdb",
        center_x=1.0,
        center_y=2.0,
        center_z=3.0,
        size_x=20.0,
        size_y=20.0,
        size_z=20.0,
    ).executable == str(gnina)
    aizynth = AiZynthFinderConfig()
    assert aizynth.executable == str(aizynthcli)
    assert aizynth.config_path == str(config_yml)
    predictor = OpenADMETConfig(
        endpoints=[{"output_column": "OADMET_PRED_x", "endpoint_id": "herg_pic50"}]
    )
    assert predictor.executable == str(openadmet)
    assert predictor.model_dir == (str(released),)


def test_every_declared_path_names_its_variable_and_a_way_to_get_it(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The declaration is what the preflight prints, so it has to be complete.

    A spec with no remedy produces a refusal that says an engine is missing and
    nothing about how to stop it being missing, which is the message this whole
    mechanism replaced.
    """

    for model in (
        KarmaDockConfig,
        GninaConfig,
        UniDockConfig,
        AiZynthFinderConfig,
        Boltz2Config,
        OpenADMETConfig,
    ):
        specs = model.installed_paths()
        assert specs, f"{model.__name__} calls out to another process and declares no paths"
        for spec in specs:
            assert spec.variable(model.engine_id).startswith("MOLCASCADE_")
            assert spec.label and not spec.label.startswith(spec.field)
            assert spec.candidates, f"{model.__name__}.{spec.field} has nowhere to look"
            assert spec.remedy, f"{model.__name__}.{spec.field} names no way to install it"
            for candidate in spec.candidates:
                assert candidate.is_absolute()
